pytestmark = pytest.mark.postgres


class _TaxonomyModule(ModuleBase):
    meta = ModuleMeta(name="taxonomy")

    def db_extensions(self) -> list[str]:
        return ["ltree"]


def _metadata() -> sa.MetaData:
    md = sa.MetaData()
    sa.Table(
        "dbext_node",
        md,
        sa.Column("id", sa.Integer, primary_key=True),
        sa.Column("path", LTree(), nullable=False),
        sa.Column("search", TSVector()),
    )
    return md


@pytest.fixture
def pg_engine():
    url = database_url_for_tests().replace("+asyncpg", "+psycopg2")
    engine = sa.create_engine(url)
    with engine.begin() as conn:
        conn.execute(sa.text("DROP TABLE IF EXISTS dbext_node"))
    yield engine
    with engine.begin() as conn:
        conn.execute(sa.text("DROP TABLE IF EXISTS dbext_node"))
    engine.dispose()


def test_ensure_db_extensions_is_idempotent(pg_engine):
    with pg_engine.begin() as conn:
        assert ensure_db_extensions(conn, [_TaxonomyModule()]) == ["ltree"]
        assert ensure_db_extensions(conn, [_TaxonomyModule()]) == ["ltree"]
        assert conn.execute(sa.text("SELECT 1 FROM pg_extension WHERE extname='ltree'")).scalar()


def test_ltree_and_tsvector_queries(pg_engine):
    md = _metadata()
    table = md.tables["dbext_node"]
    with pg_engine.begin() as conn:
        ensure_db_extensions(conn, [_TaxonomyModule()])
        md.create_all(conn)
        conn.execute(
            table.insert().values(
                id=1, path="top.science", search=sa.func.to_tsvector("english", "red fox")
            )
        )
        conn.execute(
            table.insert(),
            [{"id": 2, "path": "top.science.physics"}, {"id": 3, "path": "top.arts"}],
        )
        under = conn.execute(
            sa.select(table.c.id).where(table.c.path.op("<@")(sa.literal("top.science", LTree())))
        ).scalars()
        assert sorted(under) == [1, 2]
        hit = conn.execute(
            sa.select(table.c.id).where(
                table.c.search.op("@@")(sa.func.plainto_tsquery("english", "fox"))
            )
        ).scalars()
        assert list(hit) == [1]


def test_autogenerated_migration_round_trips(pg_engine):
    """Autogenerate -> upgrade -> downgrade -> upgrade -> no drift left."""
    md = _metadata()
    with pg_engine.begin() as conn:
        ensure_db_extensions(conn, [_TaxonomyModule()])
        mc = MigrationContext.configure(conn, opts={"render_item": render_item})
        ops = produce_migrations(mc, md)
        assert ops.upgrade_ops is not None
        auto = AutogenContext(
            mc,
            md,
            opts={
                "render_item": render_item,
                "sqlalchemy_module_prefix": "sa.",
                "alembic_module_prefix": "op.",
                "user_module_prefix": None,
                "render_as_batch": False,
            },
        )
        upgrade = "\n".join(render_op_text(auto, op) for op in ops.upgrade_ops.ops)
        downgrade = "\n".join(render_op_text(auto, op) for op in ops.upgrade_ops.reverse().ops)
        assert "simple_module_db.types.LTree()" in upgrade
        assert "simple_module_db.types.TSVector()" in upgrade

        # The generated imports alone must make the code runnable.
        namespace: dict = {"op": Operations(mc)}
        exec("import sqlalchemy as sa\n" + "\n".join(sorted(auto.imports)), namespace)

        def run(code: str) -> None:
            with Operations.context(mc):
                exec(code, namespace)

        def has_table() -> bool:
            return sa.inspect(conn).has_table("dbext_node")

        run(upgrade)
        assert has_table()
        # No "Did not recognize type 'ltree'" warning: reflection knows LTree.
        with warnings.catch_warnings():
            warnings.simplefilter("error", SAWarning)
            assert compare_metadata(mc, md) == []
        run(downgrade)
        assert not sa.inspect(conn).has_table("dbext_node")
        run(upgrade)
        assert has_table()


async def test_reset_schema_recreates_declared_extensions(monkeypatch):
    from simple_module_core import discovery
    from simple_module_test.database import init_db_kwargs, reset_schema
    from sqlalchemy.ext.asyncio import create_async_engine

    monkeypatch.setattr(discovery, "discover_modules", lambda *a, **k: [_TaxonomyModule()])
    url = database_url_for_tests()
    engine = create_async_engine(url, **init_db_kwargs(url))
    try:
        await reset_schema(engine)
        async with engine.connect() as conn:
            found = await conn.execute(sa.text("SELECT 1 FROM pg_extension WHERE extname='ltree'"))
            assert found.scalar() == 1
    finally:
        await engine.dispose()

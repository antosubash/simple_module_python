"""``smpy openapi gen-types`` — per-module TypeScript types for the API client (#504).

Each module's ``/api`` operations (its first OpenAPI tag is ``ModuleMeta.name``)
are cut out of the host's in-memory schema, with only the component schemas
they reach, and run through ``openapi-typescript``. The result lands in
``<package>/pages/api.generated.ts``, which ``pages/api.ts`` feeds to
``createApi<paths>()`` from ``@simple-module-py/ui``.

Standard library only: the CLI package carries no framework dependencies
(``test_no_framework_deps``); the caller hands in the schema and module list.
"""

from __future__ import annotations

import importlib
import json
import shutil
import subprocess
import tempfile
from collections.abc import Callable, Iterable, Iterator
from dataclasses import dataclass
from pathlib import Path
from typing import Any

#: Pinned so every checkout (and CI's freshness check) emits identical files.
#: Keep in step with ``packages/ui/package.json`` devDependencies.
OPENAPI_TYPESCRIPT_VERSION = "7.13.0"
GENERATED_FILENAME = "api.generated.ts"
_TOOL = "openapi-typescript"
_REF_PREFIX = "#/components/schemas/"
_HEADER = (
    "// AUTO-GENERATED by `smpy openapi gen-types` from the {name} module's /api\n"
    "// operations — do not edit. Regenerate with `smpy openapi gen-types --module {package}`\n"
    "// (`make gen-api-types` in the framework repo).\n"
)

Runner = Callable[..., subprocess.CompletedProcess]


class GenTypesError(RuntimeError):
    """A module could not be generated; the message is shown to the user."""


@dataclass(frozen=True)
class Target:
    name: str  # ModuleMeta.name — the OpenAPI tag
    package: str
    pages_dir: Path

    @property
    def output(self) -> Path:
        return self.pages_dir / GENERATED_FILENAME


def norm(name: str) -> str:
    """``feature_flags``, ``feature-flags`` and the ``FeatureFlags`` tag compare equal."""
    return name.replace("_", "").replace("-", "").lower()


def filter_operations(schema: dict, modules: Iterable[str]) -> dict:
    """Keep operations whose first tag is one of ``modules`` (case and underscores ignored)."""
    wanted = {norm(m) for m in modules}
    paths: dict = {}
    for path, item in schema.get("paths", {}).items():
        kept = {
            method: op
            for method, op in item.items()
            if isinstance(op, dict) and norm((op.get("tags") or [""])[0]) in wanted
        }
        if kept:
            paths[path] = kept
    return {**schema, "paths": paths}


def _refs(node: Any) -> Iterator[str]:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith(_REF_PREFIX):
            yield ref.removeprefix(_REF_PREFIX)
        for value in node.values():
            yield from _refs(value)
    elif isinstance(node, list):
        for value in node:
            yield from _refs(value)


def prune_components(schema: dict) -> dict:
    """Drop component schemas the remaining paths never reach (transitively)."""
    available = schema.get("components", {}).get("schemas", {})
    seen: set[str] = set()
    pending = list(_refs(schema.get("paths", {})))
    while pending:
        name = pending.pop()
        if name in seen or name not in available:
            continue
        seen.add(name)
        pending.extend(_refs(available[name]))
    schemas = {name: body for name, body in available.items() if name in seen}
    return {**schema, "components": {"schemas": schemas}}


def untyped_operations(schema: dict) -> list[str]:
    """``METHOD /path`` of each operation whose JSON success body has no schema."""
    found = []
    for path, item in schema.get("paths", {}).items():
        for method, op in item.items():
            for status, response in (op.get("responses") or {}).items():
                if not str(status).startswith("2"):
                    continue
                media = (response.get("content") or {}).get("application/json")
                if media is not None and not media.get("schema"):
                    found.append(f"{method.upper()} {path}")
    return found


def module_targets(modules: Iterable[Any], project_root: Path, wanted: list[str]) -> list[Target]:
    """Modules to generate: every ``wanted`` one, else those already opted in.

    A module opts in by having ``pages/api.generated.ts``. Only modules whose
    source lives under ``project_root`` are written — an installed wheel's
    copy is never touched.
    """
    root = project_root.resolve()
    targets: list[Target] = []
    found: set[str] = set()
    for module in modules:
        package = type(module).__module__.split(".")[0]
        name = module.meta.name
        keys = {norm(name), norm(package)}
        pages_dir = Path(importlib.import_module(package).__file__ or "").parent / "pages"
        target = Target(name=name, package=package, pages_dir=pages_dir)
        if wanted:
            if not keys & {norm(w) for w in wanted}:
                continue
            found |= keys
            if not pages_dir.resolve().is_relative_to(root):
                raise GenTypesError(f"{package} is installed outside {root}; not writing into it")
            targets.append(target)
        elif target.output.is_file() and pages_dir.resolve().is_relative_to(root):
            targets.append(target)
    missing = [w for w in wanted if norm(w) not in found]
    if missing:
        raise GenTypesError(f"no installed module named {', '.join(missing)}")
    return targets


def tool_command(project_root: Path) -> tuple[list[str], Path | None] | None:
    """How to run openapi-typescript, and the cwd to run it in.

    A local install wins (the framework repo pins it in ``packages/ui``); else
    ``npx`` fetches the pinned version, run from a temp dir so a project-level
    TypeScript 7 does not shadow the TypeScript 5 the tool needs.
    """
    for bin_dir in ("node_modules/.bin", "packages/ui/node_modules/.bin"):
        local = project_root / bin_dir / _TOOL
        if local.is_file():
            return [str(local)], None
    npx = shutil.which("npx")
    if npx is None:
        return None
    return [npx, "--yes", f"{_TOOL}@{OPENAPI_TYPESCRIPT_VERSION}"], Path(tempfile.gettempdir())


def render(
    schema: dict, target: Target, command: list[str], cwd: Path | None, runner: Runner
) -> str:
    """Run the tool over ``schema`` and return the file body with the header."""
    with tempfile.TemporaryDirectory() as tmp:
        src, out = Path(tmp) / "openapi.json", Path(tmp) / "out.ts"
        src.write_text(json.dumps(schema), encoding="utf-8")
        result = runner(
            [*command, str(src), "--output", str(out)],
            cwd=cwd,
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode != 0 or not out.is_file():
            raise GenTypesError(f"{_TOOL} failed for {target.package}:\n{result.stderr.strip()}")
        body = out.read_text(encoding="utf-8")
    return _HEADER.format(name=target.name, package=target.package) + body


def generate(
    schema: dict,
    targets: list[Target],
    project_root: Path,
    *,
    runner: Runner = subprocess.run,
) -> list[tuple[Target, bool, list[str]]]:
    """Write each target's file; return ``(target, changed, untyped operations)``."""
    resolved = tool_command(project_root)
    if resolved is None:
        raise GenTypesError(f"npx not found: install Node.js, or `npm i -D {_TOOL}`")
    command, cwd = resolved
    results = []
    for target in targets:
        subset = prune_components(filter_operations(schema, [target.name]))
        text = render(subset, target, command, cwd, runner)
        current = target.output.read_text(encoding="utf-8") if target.output.is_file() else None
        if current != text:
            target.output.parent.mkdir(parents=True, exist_ok=True)
            target.output.write_text(text, encoding="utf-8")
        results.append((target, current != text, untyped_operations(subset)))
    return results
